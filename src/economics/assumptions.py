REGISTER: list[Quantity] = MEASURED + ASSUMED + UNVERIFIED
BY_NAME: dict[str, Quantity] = {q.name: q for q in REGISTER}


def get(name: str) -> Quantity:
    return BY_NAME[name]


def audit() -> dict:
    """Check the register obeys its own rules, and report what the result rests on."""
    for q in UNVERIFIED:
        assert not q.status.quotable_as_point
        assert q.value is None, f"{q.name} smuggled in a point value"

    names = [q.name for q in REGISTER]
    assert len(names) == len(set(names)), "duplicate quantity in the register"

    return {
        "counts": {s.value: sum(1 for q in REGISTER if q.status is s) for s in Status},
        "headline_depends_on": {
            "measured": [q.name for q in MEASURED],
            "assumed_swept": [q.name for q in ASSUMED],
            "unverified_swept": ["mitigation_to_loss_ratio"],
        },
        "never_point_quoted": [q.name for q in UNVERIFIED],
    }


def to_json() -> dict:
    return {
        "register": [
            {
                "name": q.name,
                "status": q.status.value,
                "unit": q.unit,
                "value": q.value,
                "low": q.low,
                "high": q.high,
                "span_decades": q.span_decades,
                "quotable_as_point": q.status.quotable_as_point,
                "source": q.source,
                "note": q.note,
            }
            for q in REGISTER
        ],
        "audit": audit(),
    }


def main() -> int:
    report = to_json()

    print(f"{'quantity':<34} {'status':<11} {'value / range':>26}  unit")
    print("-" * 92)
    for q in REGISTER:
        if q.value is not None:
            shown = f"{q.value:,.6g}"
        else:
            shown = f"{q.low:,.4g} .. {q.high:,.4g}"
        flag = "" if q.status.quotable_as_point else "  <- SWEEP ONLY"
        print(f"{q.name:<34} {q.status.value:<11} {shown:>26}  {q.unit}{flag}")

    a = report["audit"]
    print(f"\nCounts: " + "  ".join(f"{k} {v}" for k, v in a["counts"].items() if v))
    print(f"\nThe headline result (screen efficiency) consumes only:")
    print(f"  measured:          {', '.join(a['headline_depends_on']['measured'][:3])}, ...")
    print(f"  assumed, swept:    {', '.join(a['headline_depends_on']['assumed_swept'])}")
    print(f"  unverified, swept: {', '.join(a['headline_depends_on']['unverified_swept'])}")
    print(f"\nNever quoted as a point value: {', '.join(a['never_point_quoted'])}")

    C.OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    out = C.OUTPUT_DIR / "assumption_register.json"
    out.write_text(json.dumps(report, indent=2))
    print(f"\nWrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
