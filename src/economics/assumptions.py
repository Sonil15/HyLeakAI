"""The assumption register — every input the economics consumes, with its status.

This is the module that decides which numbers are allowed on a slide.

`src/config.py` tags physical constants [DATASET] / [DERIVED] / [ASSUMED].
Economics needs one more tag than physics did, because it reaches for quantities
that are not ours to derive at all — a workover cost, a hydrogen price. Those get
[UNVERIFIED], and the rule attached to that tag is absolute: an UNVERIFIED
quantity may be swept, and may never be reported as a point value.

`Build_Plan.md` explains why the bar is set here rather than at "sounds about
right": the project's own `Data_sources_research.md` was AI-generated and shipped
fabricated datasets and an inverted viscosity claim. The instruction it drew from
that was: do not accept a price figure from anyone, including a model, without a
source you have opened. Nobody on this team has opened a source for a workover
cost, so no workover cost gets a point value.

WHAT SURVIVES THE RULE

Very little, and that is the point. The quantities that come out MEASURED are the
ones we generated ourselves on held-out data — classifier skill, the surrogate's
degradation against the simulator, screening latency. The economics is built so
that its headline output depends only on those, and the UNVERIFIED quantities
enter only as swept ranges that shape the envelope around it.

Usage:
    python -m src.economics.assumptions
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from enum import Enum

from src import config as C


class Status(str, Enum):
    """Provenance of a quantity. Ordered from strongest to weakest."""

    DATASET = "DATASET"        # straight out of the Mao et al. simulations
    MEASURED = "MEASURED"      # we measured it ourselves, on held-out data
    DERIVED = "DERIVED"        # computed from DATASET/MEASURED quantities
    ASSUMED = "ASSUMED"        # a documented modelling choice, swept
    UNVERIFIED = "UNVERIFIED"  # no source we have opened. SWEPT ONLY, NEVER A POINT.

    @property
    def quotable_as_point(self) -> bool:
        """May this appear on a slide as a single number?"""
        return self is not Status.UNVERIFIED


@dataclass(frozen=True)
class Quantity:
    """One input to the economics, with everything needed to defend it."""

    name: str
    status: Status
    unit: str
    source: str
    value: float | None = None
    low: float | None = None
    high: float | None = None
    note: str = ""

    def __post_init__(self) -> None:
        if self.status is Status.UNVERIFIED:
            assert self.low is not None and self.high is not None, (
                f"{self.name} is UNVERIFIED and must carry a sweep range")
            assert self.value is None, (
                f"{self.name} is UNVERIFIED and must not carry a point value — "
                f"got {self.value}. This is the check that keeps an invented "
                f"number off a slide; fix the register, not this assertion.")
        else:
            assert self.value is not None, f"{self.name} needs a value"

    @property
    def span_decades(self) -> float | None:
        """Orders of magnitude spanned by the sweep, for ranking uncertainty."""
        if self.low is None or self.high is None or self.low <= 0:
            return None
        import math
        return math.log10(self.high / self.low)


